def _load_locale_overrides() -> None:
    """Overlay editable locale resources without coupling them to analysis code."""
    locale_dir = Path(__file__).with_name("locales")
    for language in ("en", "tr"):
        path = locale_dir / f"{language}.json"
        try:
            with path.open(encoding="utf-8") as source:
                values = json.load(source)
            if isinstance(values, dict):
                STRINGS[language].update({str(key): str(value) for key, value in values.items()})
        except (OSError, json.JSONDecodeError):
            # The built-in dictionary keeps the interface usable if a resource is absent.
            continue


_load_locale_overrides()



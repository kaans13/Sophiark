def localize_text(value):
    """Translate a presentation string only when the active UI is English."""
    if isinstance(value, list):
        return [localize_text(item) for item in value]
    if isinstance(value, tuple):
        return tuple(localize_text(item) for item in value)
    if locale() != "en" or not isinstance(value, str):
        return value
    translated = value
    for source, target in sorted(EN_REPLACEMENTS.items(), key=lambda item: len(item[0]), reverse=True):
        translated = translated.replace(source, target)
    return translated


def install_streamlit_localization() -> None:
    """Apply the central presentation translator to Streamlit output surfaces.

    This covers legacy literals in root and component renderers without
    changing calculation inputs or option values. It is idempotent.
    """
    try:
        from streamlit.delta_generator import DeltaGenerator
    except Exception:
        return
    if getattr(DeltaGenerator, "_sophiark_locale_installed", False):
        return

    def wrap(method):
        original = getattr(DeltaGenerator, method, None)
        if original is None:
            return
        @wraps(original)
        def localized(self, *args, **kwargs):
            if args:
                args = (localize_text(args[0]), *args[1:])
            else:
                for name in ("body", "label", "text"):
                    if name in kwargs:
                        kwargs[name] = localize_text(kwargs[name])
                        break
            return original(self, *args, **kwargs)
        setattr(DeltaGenerator, method, localized)

    names = (
        "markdown", "caption", "info", "warning", "error", "success", "write",
        "button", "download_button", "checkbox", "toggle", "radio", "selectbox",
        "multiselect", "select_slider", "segmented_control", "text_input", "number_input",
        "slider", "expander", "tabs", "title", "header", "subheader", "status",
        "spinner", "metric", "toast",
    )
    for name in names:
        wrap(name)
    # The module-level ``st.*`` convenience methods can be pre-bound in some
    # Streamlit versions, so wrap them too. Container methods are covered by
    # DeltaGenerator above.
    for name in names:
        original = getattr(st, name, None)
        if original is None:
            continue
        @wraps(original)
        def localized_global(*args, _original=original, **kwargs):
            if args:
                args = (localize_text(args[0]), *args[1:])
            else:
                for field in ("body", "label", "text"):
                    if field in kwargs:
                        kwargs[field] = localize_text(kwargs[field])
                        break
            return _original(*args, **kwargs)
        setattr(st, name, localized_global)
    column_config = getattr(st, "column_config", None)
    if column_config is not None:
        for name in ("TextColumn", "NumberColumn", "CheckboxColumn", "SelectboxColumn", "LinkColumn", "ProgressColumn", "DateColumn"):
            original = getattr(column_config, name, None)
            if original is None:
                continue
            @wraps(original)
            def localized_column(*args, _original=original, **kwargs):
                if args:
                    args = (localize_text(args[0]), *args[1:])
                elif "label" in kwargs:
                    kwargs["label"] = localize_text(kwargs["label"])
                if "help" in kwargs:
                    kwargs["help"] = localize_text(kwargs["help"])
                return _original(*args, **kwargs)
            setattr(column_config, name, localized_column)
    DeltaGenerator._sophiark_locale_installed = True


def locale() -> str:
    return str(st.session_state.get("ui_locale", "en")).lower()


def t(key: str) -> str:
    return STRINGS.get(locale(), STRINGS["en"]).get(key, STRINGS["en"].get(key, key))
